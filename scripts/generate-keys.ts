// Creates the Ed25519 key pair that signs feed.json and rules.json.
//
//   npm run keys:generate                 production key, private half saved outside the repo
//   npm run keys:generate -- --test       throwaway key for the end-to-end tests
//
// The private key never goes into the repository. Put its contents in the
// FEED_SIGNING_KEY secret of the GitHub repository and keep a backup.

import { generateKeyPairSync } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const test = process.argv.includes('--test');

const { publicKey, privateKey } = generateKeyPairSync('ed25519');
const pem = privateKey.export({ format: 'pem', type: 'pkcs8' }).toString();
const jwk = publicKey.export({ format: 'jwk' }) as { x: string };
const pub = Buffer.from(jwk.x, 'base64url').toString('base64');

if (test) {
  const keyPath = resolve(root, 'tests/fixtures/test-signing-key.pem');
  mkdirSync(dirname(keyPath), { recursive: true });
  writeFileSync(keyPath, pem);
  writeFileSync(
    resolve(root, '.env.e2e'),
    `# Test-only values for the end-to-end build, never used in a release\nWXT_FEED_BASE=http://127.0.0.1:47123/feed/v1/\nWXT_FEED_PUBKEY=${pub}\n`,
  );
  console.log('Test key written to tests/fixtures/test-signing-key.pem and .env.e2e');
} else {
  // Default to the home folder, which is outside every git working tree.
  const outDir = resolve(process.argv.find((a) => a.startsWith('--out='))?.slice(6) ?? resolve(homedir(), 'clickfix-warden-keys'));
  const keyPath = resolve(outDir, 'feed-signing-key.pem');
  if (existsSync(keyPath)) {
    console.error(`Refusing to overwrite ${keyPath}. Move it away first if you really want a new key.`);
    process.exit(1);
  }
  mkdirSync(outDir, { recursive: true });
  writeFileSync(keyPath, pem, { mode: 0o600 });
  writeFileSync(
    resolve(root, 'src/feed/public-key.ts'),
    `// Public half of the key that signs feed.json and rules.json, generated by scripts/generate-keys.ts.\nexport const FEED_PUBLIC_KEY = '${pub}';\n`,
  );
  console.log(`Private key: ${keyPath}`);
  console.log(`Public key:  ${pub} (written to src/feed/public-key.ts)`);
}
